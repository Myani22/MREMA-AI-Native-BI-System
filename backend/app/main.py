import os
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from sqlalchemy import inspect, text
from sqlalchemy.exc import SQLAlchemyError

from app.db import SessionLocal, engine, init_db
from app.importer import import_csv_bytes
from app.models import Base, Dataset


MAX_UPLOAD_BYTES = int(os.getenv("MAX_UPLOAD_MB", "200")) * 1024 * 1024
ALLOWED_ORIGINS = [
    item.strip()
    for item in os.getenv(
        "CORS_ORIGINS", "http://localhost:5173,http://localhost:3000"
    ).split(",")
    if item.strip()
]


@asynccontextmanager
async def lifespan(app: FastAPI):
    init_db()
    Base.metadata.create_all(bind=engine)
    yield


app = FastAPI(
    title="MREMA AI-Native BI API",
    version="0.1.0",
    description="Initial API for CSV import and dataset inspection.",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["*"],
)


@app.get("/health")
def health():
    try:
        with engine.connect() as conn:
            conn.execute(text("SELECT 1"))
        return {"status": "ok", "database": "connected"}
    except SQLAlchemyError:
        raise HTTPException(status_code=503, detail="Database unavailable")


@app.get("/api/datasets")
def list_datasets():
    with SessionLocal() as session:
        items = session.query(Dataset).order_by(Dataset.created_at.desc()).all()
        return [
            {
                "id": item.id,
                "original_filename": item.original_filename,
                "table_name": item.table_name,
                "row_count": item.row_count,
                "columns": item.columns_profile,
                "created_at": item.created_at.isoformat() if item.created_at else None,
            }
            for item in items
        ]


@app.post("/api/datasets/import", status_code=201)
async def upload_csv(file: UploadFile = File(...)):
    filename = file.filename or "upload.csv"
    if Path(filename).suffix.lower() != ".csv":
        raise HTTPException(status_code=415, detail="Поддерживаются только CSV-файлы.")

    content = await file.read(MAX_UPLOAD_BYTES + 1)
    if len(content) > MAX_UPLOAD_BYTES:
        raise HTTPException(
            status_code=413,
            detail=f"Файл превышает лимит {MAX_UPLOAD_BYTES // (1024 * 1024)} MiB.",
        )
    if not content:
        raise HTTPException(status_code=400, detail="Файл пуст.")

    try:
        return import_csv_bytes(content, filename, engine)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    except Exception as exc:
        # In production, log full exception server-side; don't return SQL internals.
        raise HTTPException(status_code=500, detail="Ошибка импорта CSV.") from exc


@app.get("/api/datasets/{dataset_id}")
def get_dataset(dataset_id: int):
    with SessionLocal() as session:
        item = session.get(Dataset, dataset_id)
        if item is None:
            raise HTTPException(status_code=404, detail="Датасет не найден.")
        return {
            "id": item.id,
            "original_filename": item.original_filename,
            "table_name": item.table_name,
            "row_count": item.row_count,
            "columns": item.columns_profile,
            "created_at": item.created_at.isoformat() if item.created_at else None,
        }


@app.get("/api/datasets/{dataset_id}/preview")
def preview_dataset(dataset_id: int, limit: int = 20, offset: int = 0):
    if limit < 1 or limit > 100:
        raise HTTPException(status_code=422, detail="limit должен быть от 1 до 100.")
    if offset < 0:
        raise HTTPException(status_code=422, detail="offset не может быть отрицательным.")

    with SessionLocal() as session:
        item = session.get(Dataset, dataset_id)
        if item is None:
            raise HTTPException(status_code=404, detail="Датасет не найден.")
        table_name = item.table_name

    # table_name is generated by this service (not user-provided).
    with engine.connect() as conn:
        columns = [
            col["name"]
            for col in inspect(engine).get_columns(table_name, schema="data")
        ]
        result = conn.execute(
            text(f'SELECT * FROM data."{table_name}" LIMIT :lim OFFSET :off'),
            {"lim": limit, "off": offset},
        )
        rows = [dict(row._mapping) for row in result.fetchall()]

    return {
        "dataset_id": dataset_id,
        "columns": columns,
        "rows": rows,
        "limit": limit,
        "offset": offset,
        "row_count": item.row_count,
    }


