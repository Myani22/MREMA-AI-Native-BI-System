def render_intents(allowed: list[Intent]) -> str:
    return "\n".join(f"- {i.value}: {INTENT_DESCRIPTIONS[i]}" for i in allowed)


def render_examples(allowed: list[Intent]) -> str:
    return "\n".join(f"«{q}» -> {i.value}" for q, i in ROUTER_EXAMPLES if i in allowed)


